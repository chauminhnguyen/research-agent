@dataclass
class Chunk:
    """Một đơn vị text sau khi parse."""
    idx:      int
    text:     str
    page:     int
    bbox:     Optional[tuple] = None   # (x0, y0, x1, y1)
    chunk_type: str = 'body'           # body | heading | caption | list | code | equation

    def __repr__(self):
        preview = self.text[:60].replace('\n', ' ')
        return f'Chunk(idx={self.idx}, page={self.page}, type={self.chunk_type}, text="{preview}...")'


@dataclass
class DocumentIndex:
    """Index được build một lần khi mở document."""
    chunks:      list[Chunk]          = field(default_factory=list)
    sections:    dict[str, int]       = field(default_factory=dict)  # '3.1' → chunk_idx
    figures:     dict[str, Chunk]     = field(default_factory=dict)  # '2'   → caption chunk
    tables:      dict[str, Chunk]     = field(default_factory=dict)  # '1'   → table chunk
    equations:   dict[str, Chunk]     = field(default_factory=dict)  # '4'   → equation chunk
    bibliography: dict[str, dict]     = field(default_factory=dict)  # '14'  → {title, authors, year}

    def resolve(self, ref_type: str, ref_id: str) -> Optional[str]:
        """O(1) lookup."""
        store = getattr(self, ref_type + 's', {})
        result = store.get(ref_id)
        if result is None:
            return None
        if isinstance(result, Chunk):
            return result.text
        if isinstance(result, dict):
            return json.dumps(result)
        return str(result)

    def stats(self):
        print(f'📦 DocumentIndex stats:')
        print(f'   Chunks      : {len(self.chunks)}')
        print(f'   Sections    : {len(self.sections)}')
        print(f'   Figures     : {len(self.figures)}')
        print(f'   Tables      : {len(self.tables)}')
        print(f'   Equations   : {len(self.equations)}')
        print(f'   Bibliography: {len(self.bibliography)}')

# ── Heading / figure / table / equation / bib detection ──────────────────────

SECTION_PATTERN  = re.compile(r'^(\d+(?:\.\d+)*)\s+(.+)', re.MULTILINE)
FIGURE_PATTERN   = re.compile(r'^[Ff]ig(?:ure)?[\s\.]*?(\d+[a-z]?)[\.:](.*)', re.MULTILINE)
TABLE_PATTERN    = re.compile(r'^[Tt]able\s+(\d+)[\.:](.*)',    re.MULTILINE)
EQUATION_PATTERN = re.compile(r'\\begin\{equation\}|\\\[|\$\$')  # LaTeX block start
BIB_PATTERN      = re.compile(
    r'\[(\d+)\]\s+([A-Z][^,]+),\s+(.+?\.),\s+(\d{4})',
    re.MULTILINE
)


def _classify_chunk(text: str) -> str:
    t = text.strip()
    if SECTION_PATTERN.match(t) and len(t.split('\n')[0]) < 100:
        return 'heading'
    if FIGURE_PATTERN.match(t):
        return 'caption'
    if TABLE_PATTERN.match(t):
        return 'caption'
    if EQUATION_PATTERN.search(t):
        return 'equation'
    if t.startswith('    ') or re.match(r'^(Algorithm|Procedure|function)', t):
        return 'code'

    # Detect algorithm/pseudocode: lines bắt đầu bằng số + dấu hai chấm
    algo_lines = [l for l in text.split('\n') if re.match(r'^\s*\d+:\s+', l)]
    if len(algo_lines) >= 2:
        return 'code'

    return 'body'


def parse_pdf_pdfplumber(pdf_path: str) -> DocumentIndex:
    """Parse PDF bằng pdfplumber, build DocumentIndex."""
    index = DocumentIndex()
    raw_blocks = []

    with pdfplumber.open(pdf_path) as pdf:
        for page_num, page in enumerate(pdf.pages, start=1):
            # Extract words grouped by bbox blocks
            words = page.extract_words(use_text_flow=True, keep_blank_chars=False)
            if not words:
                continue

            # Group words into lines by y-coordinate tolerance
            lines, current_line, prev_y = [], [], None
            for w in words:
                if prev_y is None or abs(w['top'] - prev_y) < 5:
                    current_line.append(w['text'])
                else:
                    if current_line:
                        lines.append(' '.join(current_line))
                    current_line = [w['text']]
                prev_y = w['top']
            if current_line:
                lines.append(' '.join(current_line))

            raw_blocks.append({'page': page_num, 'lines': lines})

    # Build chunks from blocks
    chunk_idx = 0
    eq_counter = 0

    for block in raw_blocks:
        page = block['page']
        # Split block into sub-chunks on blank lines
        current_para = []
        for line in block['lines'] + ['']:
            if line.strip() == '' and current_para:
                text = '\n'.join(current_para)
                ctype = _classify_chunk(text)
                chunk = Chunk(idx=chunk_idx, text=text, page=page, chunk_type=ctype)
                index.chunks.append(chunk)

                # ── index by type ──
                if ctype == 'heading':
                    m = SECTION_PATTERN.match(text.strip())
                    if m:
                        index.sections[m.group(1)] = chunk_idx

                elif ctype == 'caption':
                    fm = FIGURE_PATTERN.match(text.strip())
                    tm = TABLE_PATTERN.match(text.strip())
                    if fm:
                        index.figures[fm.group(1)] = chunk
                    elif tm:
                        index.tables[tm.group(1)] = chunk

                elif ctype == 'equation':
                    eq_counter += 1
                    index.equations[str(eq_counter)] = chunk

                # Bibliography (inline detection)
                for m in BIB_PATTERN.finditer(text):
                    index.bibliography[m.group(1)] = {
                        'authors': m.group(2).strip(),
                        'title':   m.group(3).strip(),
                        'year':    m.group(4),
                    }

                chunk_idx += 1
                current_para = []
            elif line.strip():
                current_para.append(line)

    return index


