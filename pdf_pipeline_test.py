def parse_pdf_docling(pdf_path: str) -> DocumentIndex:
    """Parse PDF bằng Docling — tốt hơn cho multi-column, figures, tables."""
    try:
        from docling.document_converter import DocumentConverter
    except ImportError:
        print('❌ Docling not installed. Run: !pip install docling')
        return DocumentIndex()

    converter = DocumentConverter()
    result    = converter.convert(pdf_path)
    doc       = result.document

    index      = DocumentIndex()
    eq_counter = 0

    for chunk_idx, element in enumerate(doc.texts):
        text   = element.text
        page   = element.prov[0].page_no if element.prov else 1
        ctype  = _classify_chunk(text)

        # Docling provides explicit element types
        etype = type(element).__name__.lower()
        if 'section' in etype or 'heading' in etype:
            ctype = 'heading'
        elif 'figure' in etype:
            ctype = 'caption'
        elif 'table' in etype:
            ctype = 'caption'
        elif 'equation' in etype or 'formula' in etype:
            ctype = 'equation'

        chunk = Chunk(idx=chunk_idx, text=text, page=page, chunk_type=ctype)
        index.chunks.append(chunk)

        if ctype == 'heading':
            m = SECTION_PATTERN.match(text)
            if m: index.sections[m.group(1)] = chunk_idx
        elif ctype == 'caption':
            fm = FIGURE_PATTERN.match(text)
            tm = TABLE_PATTERN.match(text)
            if fm: index.figures[fm.group(1)] = chunk
            elif tm: index.tables[tm.group(1)] = chunk
        elif ctype == 'equation':
            eq_counter += 1
            index.equations[str(eq_counter)] = chunk

        for m in BIB_PATTERN.finditer(text):
            index.bibliography[m.group(1)] = {
                'authors': m.group(2).strip(),
                'title':   m.group(3).strip(),
                'year':    m.group(4),
            }

    return index


