# ── Sentence Boundary ─────────────────────────────────────────────────────────

def expand_to_sentence_boundary(text: str, highlight_end_char: int) -> str:
    """
    Mở rộng highlight đến hết câu hiện tại.
    Dùng spaCy để xử lý đúng abbreviations (et al., i.e., ...).
    """
    doc = nlp(text)
    for sent in doc.sents:
        if sent.end_char >= highlight_end_char:
            return text[:sent.end_char]
    return text  # fallback: trả về toàn bộ


# ── Code Block Boundary ───────────────────────────────────────────────────────

CODE_MARKERS = [
    'algorithm', 'procedure', 'function', 'for ', 'while ',
    'if ', 'return', 'input:', 'output:', 'def ', 'class ',
    'then', 'end if', 'end for', 'end while',
]

def is_inside_code_block(lines: list[str], highlight_line_idx: int, threshold: int = 2) -> bool:
    window = lines[max(0, highlight_line_idx-5): highlight_line_idx+5]
    score = sum(
        1 for line in window
        if any(m in line.lower() for m in CODE_MARKERS)
        or (line.startswith('    ') and line.strip())
    )
    return score >= threshold

def find_code_block_end(lines: list[str], start_idx: int) -> int:
    """Tìm dòng cuối của code block (blank line hoặc non-indented line)."""
    for i in range(start_idx, len(lines)):
        if i == start_idx:
            continue
        if not lines[i].strip() or (not lines[i].startswith('    ') and not lines[i].startswith('\t')):
            return i
    return len(lines)


# ── Equation Boundary ─────────────────────────────────────────────────────────

def is_partial_equation(text: str) -> bool:
    """True nếu text chứa LaTeX equation chưa đóng."""
    inline_unmatched = text.count('$') % 2 != 0
    block_unmatched  = text.count(r'\begin{equation}') != text.count(r'\end{equation}')
    bracket_unmatched = text.count(r'\[') != text.count(r'\]')
    dblock_unmatched  = text.count('$$') % 2 != 0
    return inline_unmatched or block_unmatched or bracket_unmatched or dblock_unmatched


# ── List Boundary ─────────────────────────────────────────────────────────────

LIST_PATTERN = re.compile(r'^(\s*[\•\-\*]|\s*\d+[\.\)])\s+')

def find_list_end(lines: list[str], start_idx: int) -> int:
    """Tìm dòng cuối của list."""
    for i in range(start_idx, len(lines)):
        if not lines[i].strip() or not LIST_PATTERN.match(lines[i]):
            return i
    return len(lines)


# ── Unified Semantic Boundary ──────────────────────────────────────────────────
def _find_algo_end(lines: list[str]) -> int:
    """
    Tìm dòng cuối của algorithm block.
    Algorithm kết thúc khi gặp dòng không phải: số+colon, keyword, math, hoặc blank.
    """
    ALGO_LINE = re.compile(
        r'^\s*(\d+:\s+'           # numbered line: "7: δ ← ..."
        r'|end\s+(if|for|while)'  # closing keywords
        r'|then$'                 # then
        r'|break$'                # break
        r'|[∑∈𝒙𝜹𝑝𝑿𝕀←≠]'        # unicode math symbols
        r'|[!<>]$'                # stray math chars from PDF parse
        r'|\s*$'                  # blank line
        r')'
    )
    last_algo_line = 0
    for i, line in enumerate(lines):
        if ALGO_LINE.match(line):
            last_algo_line = i
        elif i > 0 and last_algo_line > 0:
            # Gặp dòng body text sau khi đã có algo lines → dừng
            break
    return last_algo_line + 1

def apply_semantic_boundary(chunk: Chunk, highlight_end_char: int) -> str:
    """
    Áp dụng semantic boundary phù hợp dựa trên loại chunk.
    Trả về text đã được mở rộng đến boundary.
    """
    text  = chunk.text
    lines = text.split('\n')

    algo_lines = [l for l in lines if re.match(r'^\s*\d+:\s+', l)]
    is_code = chunk.chunk_type == 'code' or len(algo_lines) >= 2

    if chunk.chunk_type == 'equation' or is_partial_equation(text[:highlight_end_char]):
        boundary_type = 'equation'
        result = text  # equation luôn lấy toàn bộ

    elif is_code:
        boundary_type = 'code'
        # Chỉ lấy đến hết algorithm, bỏ phần body text phía sau
        end_line = _find_algo_end(lines)
        result = '\n'.join(lines[:end_line])

    elif LIST_PATTERN.match(text.split('\n')[0] if text.strip() else ''):
        boundary_type = 'list'
        end_line = find_list_end(lines, 0)
        result = '\n'.join(lines[:end_line])

    else:
        boundary_type = 'sentence'
        result = expand_to_sentence_boundary(text, highlight_end_char)

    return result, boundary_type


