@dataclass
class HighlightContext:
    highlight_text:    str
    expanded_chunks:   list[Chunk]
    boundary_text:     str
    boundary_type:     str
    resolved_refs:     list[tuple[str, str, str]]


async def process_highlight(
    index:           DocumentIndex,
    highlight_text:  str,
    highlight_chunk_idx: int,
    highlight_end_char:  int,
    window:          int  = 1,
    fetch_abstracts: bool = False,
) -> HighlightContext:
    """
    Full pipeline: window expansion → semantic boundary → cross-ref resolution.
    """
    # Step 1: Window Expansion
    expanded = expand_window(index, highlight_chunk_idx, window=window)

    # Step 2: Semantic Boundary
    highlight_chunk = index.chunks[highlight_chunk_idx]
    boundary_text, boundary_type = apply_semantic_boundary(
        highlight_chunk, highlight_end_char
    )

    # Step 3: Cross-Ref Resolution
    # Detect refs trong highlight + expanded context
    full_context = highlight_text + ' ' + ' '.join(c.text for c in expanded)
    resolved = await resolve_references(full_context, index, fetch_abstracts=fetch_abstracts)

    return HighlightContext(
        highlight_text  = highlight_text,
        expanded_chunks = expanded,
        boundary_text   = boundary_text,
        boundary_type   = boundary_type,
        resolved_refs   = resolved,
    )


def build_prompt(ctx: HighlightContext, mode: str = 'ask') -> str:
    """Build enriched prompt từ HighlightContext."""
    expanded_text = '\n---\n'.join(c.text for c in ctx.expanded_chunks)

    prompt = f"""You are analyzing an academic paper.

HIGHLIGHTED TEXT (what the user selected):
{ctx.highlight_text}

BOUNDARY TYPE DETECTED: {ctx.boundary_type}
EXPANDED TO BOUNDARY:
{ctx.boundary_text}

SURROUNDING CONTEXT (±window chunks):
{expanded_text}
"""

    if ctx.resolved_refs:
        prompt += '\nRESOLVED REFERENCES:\n'
        for ref_type, ref_id, content in ctx.resolved_refs:
            prompt += f'  [{ref_type} {ref_id}]: {content[:200]}\n'

    if mode == 'ask':
        prompt += """
Answer specifically about the highlighted text.
Use surrounding context and resolved references to inform your answer.
"""
    elif mode == 'save':
        prompt += """
Extract a complete, self-contained knowledge unit from the highlighted text.
Return JSON with: completed_text, suggested_type (concept|method|result|insight), summary.
Return ONLY JSON, no preamble.
"""

    return prompt


